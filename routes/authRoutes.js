// Imports;
const express = require("express");
const authRoutes = express.Router();
const {handleRateLimit, requirePending2FA} = require("../utils/auth");
const controllers = require("../controllers/authController");
// Website GET Signup Route;
authRoutes.get("/signup", controllers.getSignup);
// Website POST Signup Route;
authRoutes.post("/signup", handleRateLimit(3), controllers.postSignup);
// Website GET Login Route;
authRoutes.get("/login", controllers.getLogin);
// Website POST Login Route;
authRoutes.post("/login", handleRateLimit(5), controllers.postLogin);
// Website POST 2 Factor OTP Received Route;
authRoutes.post('/2Factor-OTP', handleRateLimit(3), requirePending2FA, controllers.post2fOTPReceived);
// Website POST Logout Route;
authRoutes.post("/logout", controllers.postLogout);
// Website GET Forgot Password Route;
authRoutes.get("/forgot-password", controllers.getForgotPassword);
// Website POST Forgot Password Route;
authRoutes.post("/forgot-password", handleRateLimit(3), controllers.postForgotPassword);
// Website GET Reset Password Route;
authRoutes.get("/reset-password/:token", controllers.getResetPassword);
// Website POST Reset Password Route;
authRoutes.post("/reset-password/:token", handleRateLimit(5), controllers.postResetPassword);
// Exports;
module.exports = authRoutes;
