// Imports;
const express = require("express");
const controller = require("../controllers/appController");
const appRoutes = express.Router();
// Website GET Home Route;
appRoutes.get("/", controller.getHome);
// Website GET About Route;
appRoutes.get("/about", controller.getAbout);
// Website GET Shop Route;
appRoutes.get("/shop", controller.getShop);
// Website GET Contact Route;
appRoutes.get("/contact", controller.getContact);
// Website POST Contact Route;
appRoutes.post("/contact", controller.postContact);
// Website POST Search Route;
appRoutes.get("/search", controller.getSearch);
// Website GET Serch Suggestions Route;
appRoutes.get("/search/suggestions", controller.getSearchSuggestions);
// Website POST News Letter Route;
appRoutes.post("/news-letter", controller.postNewsLetter);
// Website GET Privacy & Policy Route;
appRoutes.get("/privacy-policy", controller.getPrivacyPolicy);
// Website GET Returns Policy Route;
appRoutes.get("/returns-policy", controller.getReturnsPolicy);
// Website GET Terms Conditions Route;
appRoutes.get("/terms-conditions", controller.getTermsConditions);
// Exports;
module.exports = appRoutes;
