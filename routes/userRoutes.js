// Imports;
const express = require('express');
const {auth} = require("../utils/auth");
const {onlyFetch} = require("../utils/validate");
const {handleRateLimit} = require("../utils/auth");
const controller = require('../controllers/userController');
const userRoutes = express.Router();
// Website GET Profile Route;
userRoutes.get('/@:username/profile-overview', auth('page'), controller.getProfile);
// Website PUT Profile Edit Route;
userRoutes.put('/profile-edit', auth('api'), controller.putEditProfile);
// Website GET Address Book Route;
userRoutes.get('/@:username/address-book', auth('page'), controller.getAddressBook);
// Website GET Address Add Route;
userRoutes.get('/@:username/address-add', auth('page'), controller.getAddressAdd);
// Website POST Address Add Route;
userRoutes.post('/address-add', auth('api'), controller.postAddressAdd);
// Website GET Address Edit Route;
userRoutes.get('/@:username/address-edit/:id', auth('page'), controller.getAddressEdit);
// Website PUT Address Edit Route;
userRoutes.put('/address-edit', auth('api'), controller.putAddressEdit);
// Website POST Default Address Route;
userRoutes.post('/set-default-address/:id', auth('api'), controller.setDefaultAddress);
// Website DELETE Address Route;
userRoutes.delete('/address-delete/:id', auth('api'), controller.deleteAddress);
// Website GET Privacy & Security Route;
userRoutes.get('/@:username/privacy-security', auth('page'), controller.getPrivacySecurity);
// Website GET Favourites Route;
userRoutes.get('/@:username/favourites', auth('page'), controller.getFavourites);
// Website POST Favourite Route;
userRoutes.post('/favourites/:id', auth('api'), controller.postFavourites);
// Website DELETE Un-Favourite Route;
userRoutes.delete('/favourites/remove/:id', auth('api'), controller.removeFromFavourites);
// Website GET Cart Route;
userRoutes.get('/@:username/cart', auth('page'), controller.getCart);
// Website POST Cart Route;
userRoutes.post('/cart/:id', auth('api'), controller.postCart);
// Website PUT Cart Update Quantity Route;
userRoutes.put('/cart/quantity-update/:id', auth('api'), controller.updateCartQuantity);
// Website DELETE Remove Cart Route;
userRoutes.delete('/cart/remove/:id', auth('api'), controller.removeFromCart);
// Website GET Checkout Route;
userRoutes.get('/@:username/checkout', auth('page'), controller.getCheckout);
// Website GET Checkout Data Route;
userRoutes.get('/checkout-validations', onlyFetch, controller.checkoutValidations);
// Website POST Checkout Route;
userRoutes.post('/checkout', auth('api'), controller.postCheckout);
// Website GET Order Success Route;
userRoutes.get('/@:username/order-success/:orderId', auth('page'), controller.getOrderSuccess);
// Website GET My Order Route;
userRoutes.get('/@:username/my-orders', auth('page'), controller.getMyOrders);
// Website GET Order Tracking Route;
userRoutes.get('/@:username/order-tracking', auth('page'), controller.getOrderTracking);
// Website GET Order Tracking Route;
userRoutes.post('/order-tracking', auth('api'), controller.postOrderTracking);
// Website PUT Email Update Route;
userRoutes.put('/email-update', handleRateLimit(2), auth('api'), controller.putChangeEmail);
// Website PUT Password Update Route;
userRoutes.put('/password-update', handleRateLimit(3), auth('api'), controller.putChangePassword);
// Website PUT 2 Factor Authentication Route;
userRoutes.put('/2F-auth', handleRateLimit(2), auth('api'), controller.put2FactorAuth);
// Website POST Sign Out All Route;
userRoutes.post('/sign-out-all', auth('api'), controller.postSignOutAll);
// Website DELETE Account Route;
userRoutes.delete('/account-delete', handleRateLimit(1), auth('api'), controller.DeleteAccountAndData);
// Exports;
module.exports = userRoutes;
