// Imports;
const express = require("express");
const {auth, admin} = require("../utils/auth");
const controllers = require("../controllers/adminController");
const adminRoutes = express.Router();
// Website GET Admin Dashboard Route;
adminRoutes.get("/dashboard", auth("page"), admin, controllers.getDashboard);
// Website GET Admin Manage Products Route;
adminRoutes.get("/manage-products", auth("page"), admin, controllers.getManageProducts);
// Website GET Admin Add Product Route;
adminRoutes.get("/product-add", auth("page"), admin, controllers.getAddProduct);
// Website POST Admin Add Product Route;
adminRoutes.post("/product-add", auth("api"), admin, controllers.postAddProduct);
// Website GET Admin Edit Product Route;
adminRoutes.get("/product-edit/:id", auth("page"), admin, controllers.getEditProduct);
// Website PUT Admin Edit Product Route;
adminRoutes.put("/product-edit", auth("api"), admin, controllers.putEditProduct);
// Website DELETE Admin Product Route;
adminRoutes.delete("/product-delete/:id", auth("api"), admin, controllers.deleteProduct);
// Website GET Admin Manage Orders Route;
adminRoutes.get("/manage-orders", auth("page"), admin, controllers.getManageOrders);
// Website GET Admin Manage Users Route;
adminRoutes.get("/manage-users", auth("page"), admin, controllers.getManageUsers);
// Exports;
module.exports = adminRoutes;
